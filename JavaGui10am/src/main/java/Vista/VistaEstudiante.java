    private void btnEvaluarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEvaluarActionPerformed
        // TODO add your handling code here:
        try{
        // capturar los datos
        String nombre = txtNombre.getText().trim();
        double nota1 = Double.parseDouble(txtNota1.getText());
         double nota2 = Double.parseDouble(txtNota2.getText());
        // instanciar el objeto modelo estudiante
        Estudiante estudiante = new Estudiante(nombre,nota1,nota2);        
        //pedirle al objeto que trabaje y lo coloque en la interfaz
        String mensaje = String.format("Estudiante : %s | Definitiva: %.2f (%s)",
                         estudiante.getNombre(),
                         estudiante.calcularDefinitiva(),
                         estudiante.obtenerEstado());
        lblResultado.setText(mensaje);
        
        }catch(NumberFormatException e){
        JOptionPane.showMessageDialog(this,
                                      "por favor Ingresa  valores Numericos Validos en las notas",
                                      "error de formato",
                                      JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnEvaluarActionPerformed

